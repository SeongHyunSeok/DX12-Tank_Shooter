{
}

void CBulletObject::SetFirePosition(XMFLOAT3 xmf3FirePosition)
{
	m_xmf3FirePosition = xmf3FirePosition;
	SetPosition(xmf3FirePosition);
}

void CBulletObject::Reset()
{
	m_fElapsedTimeAfterFire = 0;
	m_fMovingDistance = 0;
	m_fFireStartTime = 0.f;
	m_xmf3Velocity = XMFLOAT3(0.0f, 0.f, 0.0f);


	m_bActive = false;
}

void CBulletObject::Animate(float fElapsedTime, XMFLOAT4X4* pxmf4x4Parent)
{
	m_fElapsedTimeAfterFire += fElapsedTime;

	float fDistance = m_fMovingSpeed * fElapsedTime;

	// 중력 작용
	XMFLOAT3 xmf3Position = GetPosition();
	if (m_xmf3Velocity.x == 0 && m_xmf3Velocity.y == 0 && m_xmf3Velocity.z == 0)
		m_xmf3Velocity = Vector3::ScalarProduct(m_xmf3MovingDirection, fDistance, false);
	//m_xmf3Velocity = Vector3::Add(m_xmf3Velocity, Vector3::ScalarProduct(m_xmf3Gravity, fElapsedTime, false));
	m_xmf3Velocity.y += m_xmf3Gravity.y * fElapsedTime;

	xmf3Position = Vector3::Add(xmf3Position, m_xmf3Velocity);

	m_xmf4x4World._41 = xmf3Position.x; m_xmf4x4World._42 = xmf3Position.y; m_xmf4x4World._43 = xmf3Position.z;
	m_fMovingDistance += fDistance;

	CGameObject::Animate(fElapsedTime);

	if ((m_fMovingDistance > m_fBulletEffectiveRange))
		Reset();
}

