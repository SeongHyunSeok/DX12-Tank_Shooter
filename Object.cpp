XMFLOAT3 CExplosiveObject::m_pxmf3SphereVectors[EXPLOSION_DEBRISES];
CMesh* CExplosiveObject::m_pExplosionMesh = NULL;

inline float RandF(float fMin, float fMax)
{
	return(fMin + ((float)rand() / (float)RAND_MAX) * (fMax - fMin));
}

XMVECTOR RandomUnitVectorOnSphere()
{
	XMVECTOR xmvOne = XMVectorSet(1.0f, 1.0f, 1.0f, 1.0f);
	XMVECTOR xmvZero = XMVectorZero();

	while (true)
	{
		XMVECTOR v = XMVectorSet(RandF(-1.0f, 1.0f), RandF(-1.0f, 1.0f), RandF(-1.0f, 1.0f), 0.0f);
		if (!XMVector3Greater(XMVector3LengthSq(v), xmvOne)) return(XMVector3Normalize(v));
	}
}

CExplosiveObject::CExplosiveObject()
{
}

CExplosiveObject::~CExplosiveObject()
{
	if (m_pExplosionMesh) m_pExplosionMesh->Release();
	if (m_pMesh) m_pMesh->Release();
	if (m_pShader)
	{
		m_pShader->ReleaseShaderVariables();
		m_pShader->Release();
	}
}

void CExplosiveObject::PrepareExplosion(CMesh* pExplosionMesh)
{
	XMFLOAT3 xmf3Position = GetPosition();
	for (int i = 0; i < EXPLOSION_DEBRISES; i++) {
		m_ppParticle[i] = new CRotatingObject();
		m_ppParticle[i]->SetMesh(pExplosionMesh);
		m_ppParticle[i]->SetRotationAxis(XMFLOAT3(0.0f, 1.0f, 0.0f));
		m_ppParticle[i]->SetRotationSpeed(20.f);
		XMStoreFloat3(&m_pxmf3SphereVectors[i], ::RandomUnitVectorOnSphere());
		m_ppParticle[i]->SetPosition(xmf3Position.x + m_pxmf3SphereVectors[i].x, xmf3Position.y + m_pxmf3SphereVectors[i].y, xmf3Position.z + m_pxmf3SphereVectors[i].z);
	}
}

void CExplosiveObject::Animate(float fElapsedTime, XMFLOAT4X4* pxmf4x4Parent)
{
	if (m_bBlowingUp)
	{
		m_fElapsedTimes += fElapsedTime;
		if (m_fElapsedTimes <= m_fDuration)
		{
			
			for (int i = 0; i < EXPLOSION_DEBRISES; i++)
			{
				XMFLOAT3 xmf3Position = m_ppParticle[i]->GetPosition();
				m_pxmf4x4Transforms[i] = Matrix4x4::Identity();
				m_pxmf4x4Transforms[i]._41 = m_pxmf3SphereVectors[i].x * m_fExplosionSpeed * m_fElapsedTimes;
				m_pxmf4x4Transforms[i]._42 = m_pxmf3SphereVectors[i].y * m_fExplosionSpeed * m_fElapsedTimes;
				m_pxmf4x4Transforms[i]._43 = m_pxmf3SphereVectors[i].z * m_fExplosionSpeed * m_fElapsedTimes;
				m_pxmf4x4Transforms[i] = Matrix4x4::Multiply(Matrix4x4::RotationAxis(m_pxmf3SphereVectors[i], m_fExplosionRotation * m_fElapsedTimes), m_pxmf4x4Transforms[i]);
				m_ppParticle[i]->SetPosition(xmf3Position.x + m_pxmf4x4Transforms[i]._41, xmf3Position.y + m_pxmf4x4Transforms[i]._42, xmf3Position.z + m_pxmf4x4Transforms[i]._43);
			}
			UpdateBoundingBox();
		}
		else
		{
			m_bBlowingUp = false;
			m_fElapsedTimes = 0.0f;
			m_bActive = false;
		}
	}
	else
	{
		CRotatingObject::Animate(fElapsedTime);
	}
}

void CExplosiveObject::Render(ID3D12GraphicsCommandList* pd3dCommandList, CCamera* pCamera)
{
	if (m_bBlowingUp)
	{
		for (int i = 0; i < EXPLOSION_DEBRISES; i++)
		{
			m_ppParticle[i]->Render(pd3dCommandList, pCamera);
		}
	}
	else
	{
		CGameObject::Render(pd3dCommandList, pCamera);
	}
}

void CExplosiveObject::SetExplosionMesh(CMesh* pExplosionMesh)
{
	if (m_pExplosionMesh) m_pExplosionMesh->Release();
	m_pExplosionMesh = pExplosionMesh;
	if (m_pExplosionMesh) m_pExplosionMesh->AddRef();
}
